#!/usr/bin/env node
'use strict';

/**
 * Install repo git hooks (pre-commit → scripts/pre-commit).
 * Invoked from npm prepare so clones get the local CI replacement.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const hooksDir = path.join(root, '.git', 'hooks');
const src = path.join(root, 'scripts', 'pre-commit');
const dest = path.join(hooksDir, 'pre-commit');

if (!fs.existsSync(path.join(root, '.git'))) {
  process.exit(0);
}
if (!fs.existsSync(src)) {
  console.warn('install-git-hooks: scripts/pre-commit missing');
  process.exit(0);
}

fs.mkdirSync(hooksDir, { recursive: true });
const body = `#!/usr/bin/env bash
# Generated by scripts/install-git-hooks.js — do not edit; change scripts/pre-commit
set -euo pipefail
ROOT="$(git rev-parse --show-toplevel)"
exec bash "$ROOT/scripts/pre-commit"
`;
fs.writeFileSync(dest, body, { mode: 0o755 });
try {
  fs.chmodSync(dest, 0o755);
} catch (_) {
  /* windows */
}
console.log('git hook installed: .git/hooks/pre-commit → scripts/pre-commit');
